'use strict';

// The generated-section markers and the text rules every generated section
// follows (instruction rewrite step 4, lane gen-docs; plan 2026-10-27
// decision 4 and the contract "The markers").
//
// A section is everything between a line `<!-- gen:<name> -->` and a line
// `<!-- /gen:<name> -->` (each alone on its line, surrounding spaces allowed).
// The marker lines stay; the body between them is the notice line, a blank
// line, the rendered section and a blank line. The names and their files are
// fixed: tree, scripts and env in README.md; routes, schema and agents in
// ARCHITECTURE.md. The generator never creates a marker.
//
//   locate(text, name)                 {problem, open, close, lines}; problem is
//                                      'missing', 'doubled', 'out of order' or
//                                      null
//   replaceSection(text, name, body, file)
//                                      {text, problem, changed}; problem names
//                                      the file and section ("README.md
//                                      gen:tree missing") and leaves the text
//                                      as it was
//   readSection(text, name)            the body between the markers, or null
//   expectedBody(body)                 what replaceSection writes between them
//   blankSection(text, name)           the text with that body emptied, or null
//                                      on a marker problem
//   plain(s), cell(s), code(s)         one-line text for a generated section: no
//                                      em dash (U+2014 becomes " - "), whitespace
//                                      runs collapsed; cell escapes pipes for a
//                                      table; code wraps a code span
//
// CRLF documents keep CRLF on the lines written between the markers.

const DOC_SECTIONS = Object.freeze({
  'README.md': Object.freeze(['tree', 'scripts', 'env']),
  'ARCHITECTURE.md': Object.freeze(['routes', 'schema', 'agents']),
});
const NOTICE = 'Generated by npm run docs; do not edit between the markers.';

const openMarker = (name) => `<!-- gen:${name} -->`;
const closeMarker = (name) => `<!-- /gen:${name} -->`;

function noEmDash(s) {
  return String(s == null ? '' : s).replace(/\s*\u2014\s*/g, ' - ');
}

function plain(s) {
  return noEmDash(s).replace(/\s+/g, ' ').trim();
}

function cell(s) {
  return plain(s).replace(/\|/g, '\\|');
}

function code(s) {
  const t = noEmDash(s).replace(/\|/g, '\\|');
  return t.includes('`') ? `\`\` ${t} \`\`` : `\`${t}\``;
}

function locate(text, name) {
  const lines = String(text == null ? '' : text).split('\n');
  const opens = [];
  const closes = [];
  lines.forEach((l, i) => {
    const t = l.trim();
    if (t === openMarker(name)) opens.push(i);
    else if (t === closeMarker(name)) closes.push(i);
  });
  if (opens.length === 0 || closes.length === 0) return { problem: 'missing', lines };
  if (opens.length > 1 || closes.length > 1) return { problem: 'doubled', lines };
  if (closes[0] < opens[0]) return { problem: 'out of order', lines };
  return { problem: null, lines, open: opens[0], close: closes[0] };
}

function bodyLines(body) {
  const b = String(body == null ? '' : body).replace(/\s+$/, '');
  return b === '' ? [NOTICE, ''] : [NOTICE, '', ...b.split('\n'), ''];
}

function expectedBody(body) {
  return bodyLines(body).join('\n');
}

function problemLine(file, name, problem) {
  return `${file ? `${file} ` : ''}gen:${name} ${problem}`;
}

function replaceSection(text, name, body, file = '') {
  const loc = locate(text, name);
  if (loc.problem) return { text, problem: problemLine(file, name, loc.problem), changed: false };
  const cr = loc.lines[loc.open].endsWith('\r') ? '\r' : '';
  const next = [
    ...loc.lines.slice(0, loc.open + 1),
    ...bodyLines(body).map((l) => l + cr),
    ...loc.lines.slice(loc.close),
  ].join('\n');
  return { text: next, problem: null, changed: next !== text };
}

function readSection(text, name) {
  const loc = locate(text, name);
  if (loc.problem) return null;
  return loc.lines.slice(loc.open + 1, loc.close).map((l) => (l.endsWith('\r') ? l.slice(0, -1) : l)).join('\n');
}

function blankSection(text, name) {
  const loc = locate(text, name);
  if (loc.problem) return null;
  return [...loc.lines.slice(0, loc.open + 1), ...loc.lines.slice(loc.close)].join('\n');
}

module.exports = {
  DOC_SECTIONS,
  NOTICE,
  openMarker,
  closeMarker,
  locate,
  replaceSection,
  readSection,
  expectedBody,
  blankSection,
  plain,
  cell,
  code,
};
