#!/usr/bin/env node
'use strict';

/*
 * comment-only-proof.js: proves a diff adds, removes or rewords nothing but
 * comments (spec 2026-10-19 section 3.7; plan 2026-10-27 step 4, lane
 * comment-proof, decision 11), the proof a comment-only receipt carries as
 * its body.
 *
 *   node scripts/comment-only-proof.js --base <sha> --tip <sha> [--out <file>]
 *   node scripts/comment-only-proof.js --staged [--out <file>]
 *
 * A range compares <base> and <tip>; --staged writes the index as a tree (git
 * write-tree, the tree a quick fix's receipt keys) and compares HEAD with it.
 * The rules are scripts/lib/commentOnly.js's: a .js, .jsx, .mjs or .cjs file
 * must parse to the same tokens and line breaks on both sides, with the same
 * compiler and ESLint directive comments; a .sql file must keep the same code
 * outside its comments, a comment counting only outside single-quoted
 * strings, double-quoted identifiers and dollar-quoted bodies, which are
 * compared byte for byte; a .sh or .env.example file must keep the same code
 * lines; a .sql, .sh or .env.example side holding a lone carriage return is
 * refused; and any other file, and any file added, deleted, renamed, copied
 * or changed in mode, is not comment-only.
 *
 * The generated docs (README.md and ARCHITECTURE.md at the root) are skipped
 * as the receipt key skips them: regenerated by every change to the tree,
 * reviewed by no lens, they never stop a comment-only receipt, and they are
 * listed so the proof says what it did not read.
 *
 * Prints one line per file (`  ok  <path>` or `  NO  <path>: <reason>`), one
 * line `  skipped (generated docs): <paths>` when any were, then
 * `comment-only: yes`, `comment-only: NO (<n> files)`,
 * `comment-only: NO (nothing but generated docs)` or
 * `comment-only: NO (empty diff)`. --out writes the proof as JSON, whatever
 * it says: {version: 1, mode: 'range' | 'staged', base, tip, tree, files:
 * [{path, ok, reason}], skipped: [path], ok}, with base and tip full shas
 * (--staged: base is HEAD, tip null) and tree the tip's tree or the staged
 * tree. The review skill passes that file to `review-receipt.js finalize
 * --kind comment-only --proof <file>`, which refuses it unless it says ok, its
 * base and tip (or staged tree) are the review's, and every file of the
 * review's diff (the generated docs aside) is ok in it.
 * A reason names lines and counts, never a word of the source.
 *
 * Exit 0 comment-only, 1 not (or git failed, one line on stderr), 2 argv
 * misuse or a ref that names no commit. The repo is the one this script lives
 * in; REVIEW_RECEIPT_ROOT names another (the receipt CLI reads the same
 * variable, so the toolchain agrees on one repo), and says so in one stderr
 * line.
 */

const fs = require('node:fs');
const path = require('node:path');
const { proveDiff } = require('./lib/commentOnly');

const REPO_ROOT = path.resolve(__dirname, '..');
const USAGE = 'usage: comment-only-proof.js --base <sha> --tip <sha> [--out <file>] | --staged [--out <file>]';
const FLAGS = Object.freeze({ '--base': 'value', '--tip': 'value', '--out': 'value', '--staged': 'bool' });

class UsageError extends Error {}

function parseArgs(argv) {
  const flags = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const kind = FLAGS[a];
    if (!kind) throw new UsageError(a.startsWith('--') ? `unknown flag ${a}` : `unexpected argument ${a}`);
    const key = a.slice(2);
    if (flags[key] !== undefined) throw new UsageError(`${a} given twice`);
    if (kind === 'bool') {
      flags[key] = true;
    } else {
      const v = argv[++i];
      if (v === undefined || v.startsWith('--')) throw new UsageError(`${a} needs a value`);
      flags[key] = v;
    }
  }
  if (flags.staged && (flags.base !== undefined || flags.tip !== undefined)) throw new UsageError('--staged or --base and --tip, not both');
  if (!flags.staged && (flags.base === undefined || flags.tip === undefined)) throw new UsageError('pass --base <sha> --tip <sha>, or --staged');
  return flags;
}

function repoRoot() {
  const env = process.env.REVIEW_RECEIPT_ROOT;
  if (env) {
    process.stderr.write(`comment-only-proof: repo ${path.resolve(env)} (REVIEW_RECEIPT_ROOT)\n`);
    return path.resolve(env);
  }
  return REPO_ROOT;
}

function main(argv) {
  let flags;
  try {
    flags = parseArgs(argv);
    const proof = proveDiff({ base: flags.base, tip: flags.tip, staged: Boolean(flags.staged), cwd: repoRoot() });
    const lines = proof.files.map((f) => (f.ok ? `  ok  ${f.path}` : `  NO  ${f.path}: ${f.reason}`));
    if (proof.skipped.length) lines.push(`  skipped (generated docs): ${proof.skipped.join(', ')}`);
    const bad = proof.files.filter((f) => !f.ok).length;
    const empty = proof.skipped.length ? 'comment-only: NO (nothing but generated docs)' : 'comment-only: NO (empty diff)';
    lines.push(proof.ok ? 'comment-only: yes' : proof.files.length === 0 ? empty : `comment-only: NO (${bad} ${bad === 1 ? 'file' : 'files'})`);
    if (flags.out !== undefined) fs.writeFileSync(flags.out, `${JSON.stringify(proof, null, 2)}\n`);
    process.stdout.write(`${lines.join('\n')}\n`);
    return proof.ok ? 0 : 1;
  } catch (err) {
    if (err instanceof UsageError || (err && err.code === 'USAGE')) {
      process.stderr.write(`${USAGE}\n  (${err.message})\n`);
      return 2;
    }
    process.stderr.write(`comment-only-proof: ${String((err && err.message) || err).split('\n')[0]}\n`);
    return 1;
  }
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { main, parseArgs };
